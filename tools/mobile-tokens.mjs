/**
 * The mobile interfaces' colours, from JSON to CSS (ADR 0009, "Look").
 *
 * Each interface keeps its raw colours for light and dark in
 * `packages/shell-ui/src/mobile/ui/<name>/tokens.json` and maps them onto the
 * names the editors already read (`--surface`, `--ink`, `--accent` …) and onto
 * its own roles (`--stol`, `--ugao` …). This writes `tokens.css` beside it, one
 * block per scheme under `:root[data-ui="<name>"][data-scheme="light|dark"]`:
 * `Themes` resolves the system's scheme once and sets `data-scheme`, so a colour
 * is written once per scheme and not three times over as in `tokens.css` of the
 * desktop.
 *
 * **It refuses to write a palette that fails its contrast.** Every pair the
 * JSON declares is computed here (WCAG 2.1 relative luminance), and below 4.5:1
 * for text or 3:1 for anything else nothing is written: a colour that cannot be
 * read does not reach a build by this route. `tools/verify-mobile-tokens.mjs`
 * checks the same and that the CSS on disk is what this writes.
 *
 * No dependency: Node's own `fs` and nothing else.
 *
 *   node tools/mobile-tokens.mjs          writes every interface's tokens.css
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const UI_DIR = resolve(ROOT, 'packages/shell-ui/src/mobile/ui');
export const SCHEMES = ['light', 'dark'];
export const MINIMUM = { text: 4.5, other: 3 };

const HEX = /^#[0-9a-fA-F]{6}$/;

/** WCAG 2.1 relative luminance of an opaque `#rrggbb`. */
export function luminance(hex) {
  const channel = (at) => {
    const value = parseInt(hex.slice(at, at + 2), 16) / 255;
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5);
}

export function contrast(a, b) {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}

/** What is wrong with the file's shape, as sentences; empty when nothing is. */
export function problems(tokens) {
  const found = [];
  if (!tokens || typeof tokens !== 'object') return ['the file is not an object'];
  const { palette = {}, roles = {}, values = {}, fixed = {}, pairs = [] } = tokens;
  if (typeof tokens.interface !== 'string' || !/^[a-z]+$/.test(tokens.interface)) found.push('"interface" is not a plain name');
  for (const [name, entry] of Object.entries(palette)) {
    for (const scheme of SCHEMES) {
      if (!HEX.test(entry?.[scheme] ?? '')) found.push(`palette "${name}" has no opaque #rrggbb for ${scheme}`);
    }
  }
  for (const [role, colour] of Object.entries(roles)) {
    if (!role.startsWith('--')) found.push(`role "${role}" is not a custom property`);
    if (!(colour in palette)) found.push(`role "${role}" names "${colour}", which is not in the palette`);
  }
  for (const [name, entry] of Object.entries(values)) {
    if (!name.startsWith('--')) found.push(`value "${name}" is not a custom property`);
    for (const scheme of SCHEMES) {
      if (typeof entry?.[scheme] !== 'string') found.push(`value "${name}" has nothing for ${scheme}`);
    }
  }
  for (const name of Object.keys(fixed)) {
    if (!name.startsWith('--')) found.push(`fixed "${name}" is not a custom property`);
  }
  const all = [...Object.keys(roles), ...Object.keys(values), ...Object.keys(fixed)];
  const twice = all.filter((name, index) => all.indexOf(name) !== index);
  if (twice.length) found.push(`defined twice: ${[...new Set(twice)].join(', ')}`);
  if (!Array.isArray(pairs) || pairs.length === 0) found.push('no contrast pair is declared');
  for (const pair of Array.isArray(pairs) ? pairs : []) {
    if (!(pair.fg in roles) || !(pair.bg in roles)) found.push(`pair ${pair.fg} on ${pair.bg} names a role that is not a colour`);
    if (!(pair.kind in MINIMUM)) found.push(`pair ${pair.fg} on ${pair.bg} has kind "${pair.kind}", not text or other`);
  }
  return found;
}

/** Every declared pair in every scheme, with its ratio and whether it holds. */
export function audit(tokens) {
  const colour = (role, scheme) => tokens.palette[tokens.roles[role]][scheme];
  return tokens.pairs.flatMap((pair) =>
    SCHEMES.map((scheme) => {
      const ratio = contrast(colour(pair.fg, scheme), colour(pair.bg, scheme));
      const minimum = MINIMUM[pair.kind];
      return { ...pair, scheme, ratio, minimum, ok: ratio >= minimum };
    }),
  );
}

/** The CSS, exactly as it is written to disk (LF line endings). */
export function render(tokens) {
  const ui = tokens.interface;
  const lines = [
    `/*`,
    ` * Generated by tools/mobile-tokens.mjs from tokens.json: edit that, then run`,
    ` * \`node tools/mobile-tokens.mjs\`. tools/verify-mobile-tokens.mjs fails while`,
    ` * this file and the JSON disagree.`,
    ` */`,
    ``,
    `:root[data-ui="${ui}"] {`,
    ...Object.entries(tokens.fixed ?? {}).map(([name, value]) => `  ${name}: ${value};`),
    `}`,
  ];
  for (const scheme of SCHEMES) {
    lines.push(``, `:root[data-ui="${ui}"][data-scheme="${scheme}"] {`, `  color-scheme: ${scheme};`);
    for (const [role, name] of Object.entries(tokens.roles)) lines.push(`  ${role}: ${tokens.palette[name][scheme].toLowerCase()};`);
    for (const [name, entry] of Object.entries(tokens.values ?? {})) lines.push(`  ${name}: ${entry[scheme]};`);
    lines.push(`}`);
  }
  return `${lines.join('\n')}\n`;
}

/** The interfaces that have a `tokens.json`, with the paths of both files. */
export async function interfaces() {
  const found = [];
  for (const entry of await readdir(UI_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const json = join(UI_DIR, entry.name, 'tokens.json');
    try {
      found.push({ name: entry.name, json, css: join(UI_DIR, entry.name, 'tokens.css'), tokens: JSON.parse(await readFile(json, 'utf8')) });
    } catch (error) {
      if (error.code !== 'ENOENT') throw new Error(`${json}: ${error.message}`);
    }
  }
  return found;
}

/* Run as a program, not when imported by the check. */
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  let failed = false;
  for (const { name, css, tokens } of await interfaces()) {
    const shape = problems(tokens);
    const weak = shape.length ? [] : audit(tokens).filter((row) => !row.ok);
    if (shape.length || weak.length) {
      failed = true;
      console.log(`${name}: not written`);
      for (const line of shape) console.log(`  ${line}`);
      for (const row of weak) console.log(`  ${row.scheme}: ${row.fg} on ${row.bg} is ${row.ratio.toFixed(2)}:1, below ${row.minimum}:1 (${row.what})`);
      continue;
    }
    await writeFile(css, render(tokens));
    console.log(`${name}: ${css}`);
  }
  process.exit(failed ? 1 : 0);
}
